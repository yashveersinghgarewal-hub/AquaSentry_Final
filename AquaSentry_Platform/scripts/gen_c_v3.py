"""Generate Firmware-ready C99 (aquanet_v3.h / aquanet_v3.c) from an AquaNet-V3 weights JSON.

Usage: python3 gen_c_v3.py <weights.json> <out_dir>
The generated code: float32 only, weights in flash (static const), no malloc, only <math.h>.
"""
import json, os, sys

d = json.load(open(sys.argv[1]))
out = sys.argv[2]
sizes = d["topology"]
assert len(sizes) == 4, "generator expects 2 hidden layers"
W = [d["weights"][f"W{i + 1}"] for i in range(3)]
B = [d["weights"][f"B{i + 1}"] for i in range(3)]
mean, std = d["normalization_moments"]["mean"], d["normalization_moments"]["std"]


def f(v):
    s = repr(float(v))
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def mat(name, M):
    rows = ",\n".join("    {" + ", ".join(f(v) for v in r) + "}" for r in M)
    return f"static const float {name}[{len(M)}][{len(M[0])}] = {{\n{rows}\n}};\n"


def vec(name, v):
    return f"static const float {name}[{len(v)}] = {{" + ", ".join(f(x) for x in v) + "};\n"


n_weights = sum(len(m) * len(m[0]) for m in W)
n_params = n_weights + sum(len(b) for b in B)
arch = "-".join(map(str, sizes))
acc = d.get("test", {}).get("exact", {}).get("accuracy_pct")

h = f"""/**
 * AquaNet-V3 ({arch}) - trained water-safety classifier for ESP32 / any C99 microcontroller.
 * GENERATED from {os.path.basename(sys.argv[1])} by scripts/gen_c_v3.py - do not edit by hand.
 *
 * - float32 only (the ESP32 has a hardware FPU), weights in flash, no malloc, only <math.h>
 * - {n_params} parameters = {n_params * 4} bytes of flash; RAM use < 200 bytes on the stack
 * - Inputs: arsenic (mg/L), pH, conductivity (uS/cm), turbidity (NTU), temperature (C)
 * - Same safety rules as the server: a rule can only make the verdict stricter.
 */
#ifndef AQUANET_V3_H
#define AQUANET_V3_H
#ifdef __cplusplus
extern "C" {{
#endif

#include "aquanet_v1.h"   /* reuses aquanet_class_t and aquanet_result_t */

#define AQUANET_V3_ARCH "{arch}"
#define AQUANET_V3_PARAMS {n_params}

aquanet_result_t aquanet_v3_predict(float arsenic_mg_l, float ph, float conductivity_us_cm,
                                    float turbidity_ntu, float temperature_c);

#ifdef __cplusplus
}}
#endif
#endif
"""

c = f"""/* AquaNet-V3 ({arch}) - GENERATED by scripts/gen_c_v3.py from {os.path.basename(sys.argv[1])}. Do not edit by hand. */
#include "aquanet_v3.h"
#include <math.h>

#define N_IN {sizes[0]}
#define N_H1 {sizes[1]}
#define N_H2 {sizes[2]}
#define N_OUT {sizes[3]}

/* Arsenic is fed in as log10(As + 0.001); then every input is standardised. */
{vec("V3_MEAN", mean)}{vec("V3_STD", std)}
{mat("V3_W1", W[0])}{vec("V3_B1", B[0])}
{mat("V3_W2", W[1])}{vec("V3_B2", B[1])}
{mat("V3_W3", W[2])}{vec("V3_B3", B[2])}
static const char *V3_CLASS_NAMES[4] = {{"Safe", "Caution", "Unsafe", "Hazardous"}};

static void raise_to(aquanet_class_t *cls, aquanet_class_t at_least, const char **reason, const char *why) {{
    if (*cls < at_least) {{ *cls = at_least; *reason = why; }}
}}

aquanet_result_t aquanet_v3_predict(float arsenic_mg_l, float ph, float conductivity_us_cm,
                                    float turbidity_ntu, float temperature_c) {{
    aquanet_result_t r;
    const float raw[N_IN] = {{arsenic_mg_l, ph, conductivity_us_cm, turbidity_ntu, temperature_c}};
    float x[N_IN], h1[N_H1], h2[N_H2], z[N_OUT];
    int i, j;

    int finite = 1;
    for (i = 0; i < N_IN; i++) if (!isfinite(raw[i])) finite = 0;
    r.is_out_of_bounds = !finite || arsenic_mg_l < 0.0f || arsenic_mg_l > 2.0f || ph < 4.5f || ph > 10.5f ||
        conductivity_us_cm < 50.0f || conductivity_us_cm > 5000.0f || turbidity_ntu < 0.0f || turbidity_ntu > 100.0f ||
        temperature_c < 5.0f || temperature_c > 45.0f;

    for (i = 0; i < N_IN; i++) {{
        float v = isfinite(raw[i]) ? raw[i] : 0.0f;
        if (i == 0) v = log10f((v > 0.0f ? v : 0.0f) + 0.001f);
        x[i] = (v - V3_MEAN[i]) / V3_STD[i];
    }}
    for (i = 0; i < N_H1; i++) {{ float s = V3_B1[i]; for (j = 0; j < N_IN; j++) s += V3_W1[i][j] * x[j]; h1[i] = s > 0.0f ? s : 0.0f; }}
    for (i = 0; i < N_H2; i++) {{ float s = V3_B2[i]; for (j = 0; j < N_H1; j++) s += V3_W2[i][j] * h1[j]; h2[i] = s > 0.0f ? s : 0.0f; }}
    for (i = 0; i < N_OUT; i++) {{ float s = V3_B3[i]; for (j = 0; j < N_H2; j++) s += V3_W3[i][j] * h2[j]; z[i] = s; }}

    float mx = z[0], sum = 0.0f;
    for (i = 1; i < N_OUT; i++) if (z[i] > mx) mx = z[i];
    for (i = 0; i < N_OUT; i++) {{ r.probabilities[i] = expf(z[i] - mx); sum += r.probabilities[i]; }}
    int best = 0;
    for (i = 0; i < N_OUT; i++) {{ r.probabilities[i] /= sum; if (r.probabilities[i] > r.probabilities[best]) best = i; }}

    r.raw_model_class = (aquanet_class_t)best;
    r.confidence_pct = r.probabilities[best] * 100.0f;
    r.entropy = aquanet_calculate_entropy(r.probabilities);
    r.high_uncertainty = r.entropy > 0.65f;

    aquanet_class_t cls = (aquanet_class_t)best;
    const char *reason = "NOMINAL_NEURAL_V3";
    if (r.is_out_of_bounds) raise_to(&cls, AQUANET_CLASS_UNSAFE, &reason, "SAFETY_OVERRIDE_OUT_OF_BOUNDS");
    if (arsenic_mg_l > 0.150f) raise_to(&cls, AQUANET_CLASS_HAZARDOUS, &reason, "SAFETY_OVERRIDE_ARSENIC_ACUTE_HAZARD");
    else if (arsenic_mg_l >= 0.050f) raise_to(&cls, AQUANET_CLASS_UNSAFE, &reason, "SAFETY_OVERRIDE_ARSENIC_EXCEEDS_BIS");
    else if (arsenic_mg_l > 0.010f) raise_to(&cls, AQUANET_CLASS_CAUTION, &reason, "POTABILITY_ADVISORY_ARSENIC_ABOVE_WHO");
    if (!r.is_out_of_bounds) {{
        if (ph < 6.0f || ph > 9.0f) raise_to(&cls, AQUANET_CLASS_UNSAFE, &reason, "SAFETY_OVERRIDE_SEVERE_PH_VIOLATION");
        else if (ph < 6.5f || ph > 8.5f) raise_to(&cls, AQUANET_CLASS_CAUTION, &reason, "POTABILITY_ADVISORY_PH_EXCEEDANCE");
        if (turbidity_ntu > 10.0f) raise_to(&cls, AQUANET_CLASS_UNSAFE, &reason, "SAFETY_OVERRIDE_HIGH_TURBIDITY");
        else if (turbidity_ntu > 5.0f) raise_to(&cls, AQUANET_CLASS_CAUTION, &reason, "POTABILITY_ADVISORY_TURBIDITY");
        if (conductivity_us_cm > 2000.0f) raise_to(&cls, AQUANET_CLASS_UNSAFE, &reason, "SAFETY_OVERRIDE_HIGH_SALINITY");
        else if (conductivity_us_cm > 1500.0f) raise_to(&cls, AQUANET_CLASS_CAUTION, &reason, "POTABILITY_ADVISORY_CONDUCTIVITY");
    }}
    if (r.high_uncertainty && cls == AQUANET_CLASS_SAFE) {{ cls = AQUANET_CLASS_CAUTION; reason = "ADVISORY_HIGH_UNCERTAINTY"; }}

    r.predicted_class = cls;
    r.override_applied = cls != (aquanet_class_t)best;
    r.reason_code = reason;
    r.predicted_class_name = V3_CLASS_NAMES[cls];
    return r;
}}
"""
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "aquanet_v3.h"), "w").write(h)
open(os.path.join(out, "aquanet_v3.c"), "w").write(c)
print(f"generated {arch}: {n_params} params, {n_params * 4} bytes")
